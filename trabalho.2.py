# ==============================================================================
# 7. VALUE-AT-RISK (VaR) E BACKTESTING
# ==============================================================================
# VaR paramétrico baseado no modelo EGARCH-t:
#   VaR_t(α) = -(μ_t + q_α(ν) · σ_t)
# onde q_α(ν) é o quantil-alpha da t-Student padronizada com ν graus de liberdade.
# Backtesting via teste de Kupiec (1995).
# ==============================================================================

print("\n" + "=" * 70)
print("7. VALUE-AT-RISK E BACKTESTING")
print("=" * 70)

mu = res_final.params.get('Const', 0.0) # constante da média condicional
nu = res_final.params['nu'] # graus de liberdade da t

def var_quantil(alpha, nu):
    """Quantil-α da t-Student padronizada (variância 1)."""
    return stats.t.ppf(alpha, df=nu) * np.sqrt((nu - 2) / nu)

q_95 = var_quantil(0.05, nu)
q_99 = var_quantil(0.01, nu)

VaR_95 = -(mu + q_95 * vol)
VaR_99 = -(mu + q_99 * vol)

# Contagem de violações (retornos abaixo do limite estimado)
viol_95 = (retorno < -VaR_95).sum()
viol_99 = (retorno < -VaR_99).sum()
n = len(retorno)

print(f"\nVaR 95%: violações = {viol_95}/{n} ({viol_95/n:.2%}, esperado 5%)")
print(f"VaR 99%: violações = {viol_99}/{n} ({viol_99/n:.2%}, esperado 1%)")


def kupiec_test(violacoes, n, alpha):
    """Teste de razão de verossimilhança de Kupiec (1995)."""
    if violacoes == 0:
        return np.nan, np.nan
    p_hat = violacoes / n
    LR = -2 * (np.log(((1 - alpha) ** (n - violacoes)) * (alpha ** violacoes)) -
               np.log(((1 - p_hat) ** (n - violacoes)) * (p_hat ** violacoes)))
    pv = 1 - stats.chi2.cdf(LR, df=1)
    return LR, pv


LR95, pv95 = kupiec_test(viol_95, n, 0.05)
LR99, pv99 = kupiec_test(viol_99, n, 0.01)
print(f"\nKupiec 95%: LR={LR95:.3f}, p={pv95:.4f}")
print(f"Kupiec 99%: LR={LR99:.3f}, p={pv99:.4f}")

resultados_var = pd.DataFrame({
    "Nível":      ["95%", "99%"],
    "Violações":  [viol_95, viol_99],
    "Taxa obs.":  [viol_95 / n, viol_99 / n],
    "Taxa esp.":  [0.05, 0.01],
    "Kupiec LR":  [LR95, LR99],
    "p-valor":    [pv95, pv99],
})
resultados_var.to_csv("resultados/var_backtesting.csv", index=False)

