# ==============================================================================
# 4. CONSTRUÇÃO DE VARIÁVEIS DUMMY DE INTERVENÇÃO
# ==============================================================================
# Box & Tiao (1975) propõem dois tipos básicos de função de intervenção:
#   • PULSO  : 1 apenas no dia do evento, 0 nos demais (choque transitório)
#   • DEGRAU : 0 antes do evento, 1 do evento em diante (choque permanente)
# ==============================================================================

def dummy_pulso(idx, data):
    """Cria dummy de pulso (efeito transitório no dia do evento)."""
    d = pd.Series(0.0, index=idx)
    data = pd.to_datetime(data)
    if data in d.index:
        d.loc[data] = 1.0
    else:
        # Se o evento caiu em fim de semana/feriado, usa o próximo pregão
        prox_idx = d.index[d.index >= data]
        if len(prox_idx) > 0:
            d.loc[prox_idx[0]] = 1.0
    return d


def dummy_degrau(idx, data):
    """Cria dummy de degrau (efeito permanente após o evento)."""
    return (idx >= pd.to_datetime(data)).astype(float)


